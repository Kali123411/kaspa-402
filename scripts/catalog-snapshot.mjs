#!/usr/bin/env node
// Regenerate lib/catalog-snapshot.js from the k402 registry: what the site serves when the registry cannot be
// reached (marked fromSnapshot). Only live, publicly reachable listings belong in it. A JS module, not JSON, so
// Node and the Next bundler load it the same way.
//
//   node scripts/catalog-snapshot.mjs https://market.kaspa-402.org > lib/catalog-snapshot.js
const base = (process.argv[2] || 'https://market.kaspa-402.org').replace(/\/$/, '');
const r = await fetch(`${base}/registry/catalog`, { headers: { accept: 'application/json' } });
if (!r.ok) { console.error(`registry answered HTTP ${r.status}`); process.exit(1); }
const cat = await r.json();
const listings = (cat.listings || []).filter((l) => l.live !== false && /^https:\/\//.test(l.endpoint || '') && !/^https?:\/\/(\d+\.|\[|localhost)/.test(l.endpoint));
const doc = { generatedAt: new Date().toISOString(), registry: base, count: listings.length, listings };
process.stdout.write(`// generated by scripts/catalog-snapshot.mjs — the registry's catalog as of ${doc.generatedAt}; do not edit\nexport default ${JSON.stringify(doc, null, 1)};\n`);
