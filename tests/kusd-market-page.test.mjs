// The /kusd/market page: pays only through the checked payer and the review sheet, keeps the operator's bounds
// in the ledger, talks to known hosts only, and ships a well-formed snapshot for the registry-down case.
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';

const read = (f) => readFileSync(new URL(`../${f}`, import.meta.url), 'utf8');
const files = [
  'pages/market.js',
  ...readdirSync(new URL('../components/kusd/market/', import.meta.url)).map((f) => `components/kusd/market/${f}`),
  ...readdirSync(new URL('../lib/kusd/market/', import.meta.url)).map((f) => `lib/kusd/market/${f}`),
];
const src = files.map(read).join('\n');

test('a payment goes through the checked quote, the ledger reserve and the review sheet — in that order (smoke check; the sheet-following logic itself is tested in kusd-market-flow.test.mjs)', () => {
  const console_ = read('components/kusd/market/AgentConsole.jsx').split('\n').filter((l) => !l.trim().startsWith('//')).join('\n');
  assert.match(console_, /followSheet\(p, review\.sheet\)/, 'the console decides void/settle/unknown through the tested reducer');
  assert.match(console_, /ledger, txid: null, sending: false, finished: false/, 'the pending flow carries its own ledger (an idle lock mid-flow cannot lose it)');
  assert.match(console_, /writeStored\(WALLET_KEY, null\)/, '"Remove from this browser" removes the keystore here too');
  const i = (re) => { const m = console_.search(re); assert.ok(m >= 0, `${re} missing`); return m; };
  assert.ok(i(/\bquote\(/) < i(/checkPolicy\(/), 'quote before the operator check');
  assert.ok(i(/checkPolicy\(/) < i(/ledger\.reserve\(/), 'operator check before the reserve');
  assert.ok(i(/ledger\.reserve\(/) < i(/review\.start\('send'/), 'reserve before the wallet is asked to sign');
  assert.match(console_, /led\.void\(p\.id\)/, 'a cancelled or refused build releases the reservation');
  assert.match(console_, /led\.settle\(p\.id, \{ txid: a\.txid \}\)/, 'a broadcast settles with the txid and later the HTTP status');
  assert.match(console_, /led\.settle\(p\.id, \{ http: 0 \}\)/, 'an unknown outcome after sending stays counted');
  assert.match(console_, /\bpresent\(/);
  assert.doesNotMatch(console_, /kc\(\)\.build|\.run\(/, 'the console never builds or broadcasts on its own');
});

test('no secret in storage keys other than the keystore; the ledger and policy keys are the market\'s own', () => {
  const keys = [...src.matchAll(/['"`](kusd\.[a-z.]+\.v\d)/g)].map((m) => m[1]);
  for (const k of keys) assert.ok(['kusd.wallet.v1', 'kusd.market.spend.v1', 'kusd.market.policy.v1', 'kusd.node'].includes(k), `unexpected storage key ${k}`);
  assert.doesNotMatch(src, /setItem\([^)]*secret/i);
});

test('known hosts only, no trackers', () => {
  assert.doesNotMatch(src, /googletagmanager|google-analytics|gtag\(|plausible|segment\.com|mixpanel|posthog/i);
  const allowed = [/^https:\/\/market\.kaspa-402\.org/, /^https:\/\/api-tn10\.kaspa\.org\//, /^https:\/\/github\.com\/Kali123411\//, /^https:\/\/p\.test\//];
  for (const u of src.match(/https?:\/\/[^\s'"`)]+/g) || []) {
    assert.ok(allowed.some((re) => re.test(u)), `unexpected host ${u}`);
  }
});

test('the bundled market snapshot is well-formed and generated by the script\'s shape', () => {
  const snap = JSON.parse(read('public/kusd/market-snapshot.json'));
  assert.ok(Number.isFinite(Date.parse(snap.generatedAt)));
  assert.ok(Array.isArray(snap.providers));
  for (const p of snap.providers) {
    assert.match(p.endpoint, /^https:\/\//, 'a bundled listing must be reachable from anywhere; LAN or http endpoints never ship');
    assert.equal(p.currency, 'kUSD');
    assert.ok(Number.isInteger(p.price_cents) && p.price_cents > 0);
    assert.match(p.payee_pubkey, /^[0-9a-f]{64}$/);
  }
  assert.ok(Array.isArray(snap.activity.settlements) && Number.isInteger(snap.activity.total_cents));
  assert.doesNotMatch(JSON.stringify(snap), /192\.168\.|127\.0\.0\.1|localhost/, 'no private addresses in the public bundle');
  for (const s of snap.activity.settlements) assert.match(s.txid, /^[0-9a-f]{64}$/);
});

test('the page is linked from /kusd and names the registry by env with the public default', () => {
  assert.match(read('pages/kusd.js'), /href="\/market"/);
  assert.match(read('components/kusd/market/useMarket.js'), /NEXT_PUBLIC_KUSD_MARKET_REGISTRY/);
  assert.match(read('components/kusd/market/useMarket.js'), /https:\/\/market\.kaspa-402\.org/);
});
